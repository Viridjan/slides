const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const indexHtml = fs.readFileSync(path.join(root, '00-indice.html'), 'utf8');
const files = [...indexHtml.matchAll(/<a\s+class="module-card[^"]*"\s+href="([^"]+\.html)"/gi)]
  .map(match => match[1])
  .filter(file => !file.startsWith('quiz-'));

const decode = value => value
  .replace(/&amp;/gi, '&').replace(/&lt;/gi, '<').replace(/&gt;/gi, '>')
  .replace(/&quot;/gi, '"').replace(/&#39;|&apos;/gi, "'")
  .replace(/&nbsp;|&#160;/gi, ' ');
const clean = value => decode(value.replace(/<[^>]+>/g, ' ')).replace(/\s+/g, ' ').trim();

const titlePattern = /^(esercizio|esercizi|esercitazione|laboratorio|mini-esercizio|progetto guidato|verifica\s*:|mettiti alla prova|tocca a te|collaudare|sfida pratica|attività guidata)/i;
const labelPattern = /^(esercizio|esercizi|esercitazione|laboratorio|attività|consegna|prova pratica|verifica pratica)\b/i;
const result = {};
const addExercise = (source, entry) => {
  (result[source] = result[source] || []).push(entry);
};

// Standalone exercise slides live in the per-area esercizi-*.html decks; each
// carries data-source="<origin deck>" so the index card of the origin module
// can link to it. Exercises embedded inside content slides (a .lbl "Esercizio"
// box on a teaching slide) stay in their module deck and are detected below.
fs.readdirSync(root)
  .filter(name => /^esercizi-.*\.html$/.test(name))
  .sort()
  .forEach(file => {
    const html = fs.readFileSync(path.join(root, file), 'utf8');
    const pattern = /<section\b([^>]*)>([\s\S]*?)<\/section>/gi;
    let match;
    let index = 0;
    while ((match = pattern.exec(html))) {
      const classes = match[1].match(/\bclass\s*=\s*["']([^"']*)["']/i)?.[1].split(/\s+/) || [];
      if (!classes.includes('slide')) continue;
      index++;
      const source = match[1].match(/\bdata-source\s*=\s*["']([^"']*)["']/i)?.[1];
      if (!source) continue;
      const title = clean(match[2].match(/<h[1-3]\b[^>]*>([\s\S]*?)<\/h[1-3]>/i)?.[1] || '');
      addExercise(source, {file, slide: index, title: title || `Esercizio ${index}`});
    }
  });

files.forEach(file => {
  const filePath = path.join(root, file);
  if (!fs.existsSync(filePath)) return;
  const html = fs.readFileSync(filePath, 'utf8');
  const slides = [];
  const pattern = /<section\b([^>]*)>([\s\S]*?)<\/section>/gi;
  let match;
  while ((match = pattern.exec(html))) {
    const classes = match[1].match(/\bclass\s*=\s*["']([^"']*)["']/i)?.[1].split(/\s+/) || [];
    if (!classes.includes('slide')) continue;
    slides.push(match[2]);
  }
  slides.forEach((body, index) => {
    if (index === 0 || index === slides.length - 1) return;
    const title = clean(body.match(/<h[1-3]\b[^>]*>([\s\S]*?)<\/h[1-3]>/i)?.[1] || '');
    const labels = [...body.matchAll(/<(?:div|span)\b[^>]*class=["'][^"']*\b(?:lbl|big)\b[^"']*["'][^>]*>([\s\S]*?)<\/(?:div|span)>/gi)]
      .map(item => clean(item[1]));
    if (!titlePattern.test(title) && !labels.some(label => labelPattern.test(label))) return;
    addExercise(file, {file, slide: index + 1, title: title || labels.find(label => labelPattern.test(label)) || 'Esercizio'});
  });
});

const output = [
  '/* Proprietà intellettuale di Francesco Antonio Binetti */',
  '// Generated by scripts/build-exercise-index.js',
  '// Do not edit by hand.',
  `globalThis.EXERCISE_INDEX = ${JSON.stringify(result, null, 2)};`,
  ''
].join('\n');

fs.writeFileSync(path.join(root, 'exercise-index.js'), output);
const total = Object.values(result).reduce((sum, exercises) => sum + exercises.length, 0);
console.log(`Wrote exercise-index.js with ${total} exercises across ${Object.keys(result).length} chapters.`);
