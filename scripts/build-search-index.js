const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const indexPath = path.join(root, '00-indice.html');
const outPath = path.join(root, 'search-index.js');

const html = fs.readFileSync(indexPath, 'utf8');

const stripTags = value => value
  .replace(/<script[\s\S]*?<\/script>/gi, ' ')
  .replace(/<style[\s\S]*?<\/style>/gi, ' ')
  .replace(/<[^>]+>/g, ' ')
  .replace(/&nbsp;/g, ' ')
  .replace(/&amp;/g, '&')
  .replace(/&lt;/g, '<')
  .replace(/&gt;/g, '>')
  .replace(/&quot;/g, '"')
  .replace(/&#39;/g, "'")
  .replace(/\s+/g, ' ')
  .trim();

const pick = (block, className) => {
  const pattern = new RegExp(`<div class="${className}[^"]*"[^>]*>([\\s\\S]*?)<\\/div>`);
  const match = block.match(pattern);
  return match ? stripTags(match[1]) : '';
};

const sectionFor = offset => {
  const before = html.slice(0, offset);
  const labelMatch = [...before.matchAll(/<div class="section-label">([\s\S]*?)<\/div>/g)].pop();
  return labelMatch ? stripTags(labelMatch[1]) : '';
};

const cards = [];
const cardPattern = /<a class="module-card[^"]*" href="([^"]+\.html)">([\s\S]*?)<\/a>/g;
let match;

while ((match = cardPattern.exec(html))) {
  const href = match[1];
  const block = match[2];
  const txtPath = path.join(root, href.replace(/\.html$/, '.txt'));
  const text = fs.existsSync(txtPath) ? fs.readFileSync(txtPath, 'utf8') : '';

  cards.push({
    href,
    section: sectionFor(match.index),
    code: pick(block, 'card-num'),
    title: pick(block, 'card-title'),
    description: pick(block, 'card-desc'),
    topics: pick(block, 'card-topics'),
    text
  });
}

const banner = [
  '// Generated by scripts/build-search-index.js',
  '// Do not edit by hand.',
  `globalThis.COURSE_SEARCH_INDEX = ${JSON.stringify(cards, null, 2)};`,
  ''
].join('\n');

fs.writeFileSync(outPath, banner);
console.log(`Wrote ${path.relative(root, outPath)} with ${cards.length} entries.`);
